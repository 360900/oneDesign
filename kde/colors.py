"""KDE color scheme (.colors) from One tokens."""
from onetokens import Color


def _set(th, bg, alt, fg=None):
    c = th.c
    fg = fg or c["text"]
    return {
        "BackgroundNormal": bg,
        "BackgroundAlternate": alt,
        "DecorationFocus": c["accent"],
        "DecorationHover": c["accent"],
        "ForegroundActive": c["accentText"],
        "ForegroundInactive": c["text2"] if fg is c["text"] else fg.with_alpha(0.7).over(bg),
        "ForegroundLink": c["accentText"],
        "ForegroundNegative": c["danger"],
        "ForegroundNeutral": c["warning"],
        "ForegroundNormal": fg,
        "ForegroundPositive": c["success"],
        "ForegroundVisited": Color.oklch(0.74 if th.dark else 0.5, 0.14, 310),
    }


def color_sets(th):
    c = th.c
    canvas = c["canvas"]
    button_bg = c["fill"].over(canvas)
    comp_bg = Color.oklch(0.24, 0.006, th.hue)
    comp = _set(th, comp_bg, Color.oklch(0.2, 0.006, th.hue), Color.oklch(0.96, 0.012, th.hue))
    comp.update(
        ForegroundInactive=Color.oklch(0.72, 0.012, th.hue),
        ForegroundActive=Color.oklch(0.78, th.chroma, th.hue),
        ForegroundLink=Color.oklch(0.78, th.chroma, th.hue),
        DecorationFocus=Color.oklch(0.74, th.chroma, th.hue),
        DecorationHover=Color.oklch(0.74, th.chroma, th.hue),
    )
    sel = _set(th, c["accent"], c["container"], c["onAccent"])
    sel.update(ForegroundActive=c["onAccent"], ForegroundInactive=c["onAccent"].with_alpha(0.75).over(c["accent"]),
               ForegroundLink=c["onAccent"], ForegroundVisited=c["onAccent"])
    sets = {
        "Colors:Window": _set(th, canvas, c["sidebar"]),
        "Colors:View": _set(th, c["surface"], c["surfaceAlt"]),
        "Colors:Button": _set(th, button_bg, c["container"]),
        "Colors:Selection": sel,
        "Colors:Tooltip": _set(th, c["float"], c["surfaceAlt"]),
        "Colors:Complementary": comp,
        "Colors:Header": _set(th, c["headerbar"], c["sidebar"]),
        "Colors:Header][Inactive": _set(th, c["headerbar"], c["sidebar"]),
    }
    return sets


def scheme(th, name, ident):
    c = th.c
    out = ["# Generated by oneDesign from tokens/one.json. Do not edit.", ""]
    disabled = {
        "Color": "56,56,56", "ColorAmount": 0, "ColorEffect": 0,
        "ContrastAmount": 0.65, "ContrastEffect": 1, "IntensityAmount": 0.1, "IntensityEffect": 2,
    }
    inactive = {
        "ChangeSelectionColor": "false", "Color": "112,111,110", "ColorAmount": 0.025, "ColorEffect": 2,
        "ContrastAmount": 0.1, "ContrastEffect": 2, "Enable": "false", "IntensityAmount": 0, "IntensityEffect": 0,
    }
    for sec, kv in (("ColorEffects:Disabled", disabled), ("ColorEffects:Inactive", inactive)):
        out.append(f"[{sec}]")
        out += [f"{k}={v}" for k, v in kv.items()]
        out.append("")
    for sec, kv in color_sets(th).items():
        out.append(f"[{sec}]")
        out += [f"{k}={v.kde}" for k, v in sorted(kv.items())]
        out.append("")
    out += ["[General]", f"ColorScheme={ident}", f"Name={name}", "shadeSortColumn=false", ""]
    out += ["[KDE]", "contrast=4", ""]
    hb = c["headerbar"]
    out += [
        "[WM]",
        f"activeBackground={hb.kde}",
        f"activeBlend={hb.kde}",
        f"activeForeground={c['text'].kde}",
        f"inactiveBackground={hb.kde}",
        f"inactiveBlend={hb.kde}",
        f"inactiveForeground={c['text3'].kde}",
        "",
    ]
    return "\n".join(out)
